#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const service = read("android-shell/app/src/main/java/app/floatphone/shell/PlayfulAppLockService.kt");
const activity = read("android-shell/app/src/main/java/app/floatphone/shell/PlayfulLockActivity.kt");
const main = read("android-shell/app/src/main/java/app/floatphone/shell/MainActivity.kt");
const executor = read("lib/tool-executor.ts");
const host = read("lib/custom-app-host-api.ts");
const runner = read("components/app-market/custom-app-runner.tsx");
const internal = read("lib/internal-capability-storage.ts");
const builtin = read("lib/builtin-apps/focus-companion-meta.ts");
const manifest = read("custom-apps/focus-companion/manifest.json");

assert.match(service, /SecureRandom\(\)/, "app-lock password must use SecureRandom");
assert.match(service, /durationMinutes\.coerceIn\(1, 360\)/, "lock duration must be capped at six hours");
assert.match(service, /durationMinutes: Int = 30/, "character app lock should default to a 30-minute session");
assert.match(service, /expiresAt/, "native lock must persist and enforce expiry");
assert.match(service, /passUntil/, "temporary pass must be tracked natively");
assert.match(internal, /给临时通行证/, "characters must have a dedicated temporary-pass tool");
assert.match(internal, /"给临时通行证"/, "temporary-pass tool name must be reserved in the internal tool registry");
assert.match(executor, /这不是你发起的应用锁/, "a character must not grant a pass for another character's lock");
assert.match(executor, /这不是你发起的应用锁，不能替别人解除/, "a character must not unlock another character's lock");
assert.doesNotMatch(executor, /可以继续逗他/, "the password-threshold response must not nudge characters into awkward teasing");
assert.match(executor, /appLockTemporaryPass\(minutes\)/, "the role tool must grant the native temporary pass");
assert.match(read("lib/device-action/bridge.ts"), /export function appLockTemporaryPass\(minutes: number\)/, "the trusted device bridge must expose the temporary-pass action");
assert.match(service, /isProtectedTarget\(context, target\)/, "protected targets must be rejected in native code");
assert.match(service, /com\.android\.settings/, "Android Settings must be protected");
assert.match(service, /monitoringAvailable/, "status must report whether foreground monitoring has a source");
assert.match(service, /缺少前台应用监测能力/, "lock activation must fail rather than pretend to work without a monitor");
assert.match(service, /current_package_updated_at/, "accessibility fallback must reject stale foreground state");
assert.match(read("android-shell/app/src/main/java/app/floatphone/shell/CallControlService.kt"), /current_package_updated_at/, "accessibility service must publish a foreground heartbeat");
assert.match(service, /now - lastShowAt > 2500L/, "returning to a blocked app must be re-intercepted promptly");
assert.match(activity, /EXTRA_OPEN_URL/, "the lock screen must deep-link back to the originating chat");
assert.match(activity, /#open-chat=/, "the lock screen must route to the original chat session");
assert.doesNotMatch(activity, /temporaryPass\(this@PlayfulLockActivity, 1\)/, "temporary passes must be granted by the character, not self-served from the lock page");
assert.doesNotMatch(activity, /紧急解除/, "the app-lock screen must not expose an emergency unlock button");
assert.match(activity, /去找TA求情/, "the lock page must offer a natural plea-for-mercy route back to the character");
assert.match(activity, /TA 的专属小手段/, "the lock page keeps the character-flavored label");
assert.match(activity, /actionButton\("确认解锁"/, "password unlock remains available when the character shares the password");
assert.doesNotMatch(service, /紧急解除/, "native app-lock notifications must not advertise an emergency exit");
assert.match(internal, /name: "锁应用"/, "the character-facing lock tool must retain its clear Chinese display name");
assert.match(internal, /name: "解锁应用"/, "the character-facing unlock tool must retain its clear Chinese display name");
assert.match(activity, /updateCountdown\(\)/, "the lock screen must show remaining lock time");
assert.match(activity, /TYPE_CLASS_NUMBER or InputType\.TYPE_NUMBER_VARIATION_PASSWORD/, "six-digit native password should use a numeric keypad");
assert.match(main, /o\.optString\("sessionId"\)/, "the native bridge must receive the originating session id");
assert.match(main, /fun appLockTemporaryPass\(minutes: Int\)/, "the native bridge must expose temporary passes to the role tool");
assert.match(executor, /sessionId: resolveAppLockChatSessionId\(characterId\)/, "the role tool must pass the character's private chat session to native");
assert.match(executor, /filter\(session => !session\.isGroup/, "the lock screen must never route negotiation to a group chat");
assert.match(executor, /durationMinutes: Math\.max\(1, Math\.min\(360/, "the role tool must clamp requested duration");
assert.doesNotMatch(host, /device\.appLock\.reveal/, "custom-app host must not expose the password reveal action");
assert.doesNotMatch(runner, /appLockReveal: function/, "custom-app SDK must not expose native password reveal");
assert.doesNotMatch(host, /password: String\(record\.password/, "custom apps must not provide their own native lock password");
assert.match(internal, /durationMinutes: \{ type: "number"/, "internal role tool schema must expose bounded duration");
assert.match(internal, /不要写成训话/, "lock-screen dialogue guidance must discourage canned scolding");
assert.match(internal, /表现好就奖励你/, "lock-screen dialogue guidance must discourage awkward reward bargaining");
assert.match(builtin, /durationMinutes/, "built-in companion manifest must document bounded duration");
assert.match(manifest, /durationMinutes/, "exported companion manifest must document bounded duration");
assert.match(manifest, /角色锁页主题与留言/, "companion tool schema must allow character-authored lock-screen copy");

console.log("Playful app-lock interaction and safety contract tests passed.");
